package dev.znlp.base.service;

/**
 * 服务工厂接口
 *
 * <p>定义了创建服务实例的工厂方法接口，用于支持服务的动态创建。</p>
 *
 * <p>服务工厂模式的核心接口，通过该接口可以：</p>
 * <ul>
 *   <li>支持单例服务的创建</li>
 *   <li>支持原型服务的创建</li>
 *   <li>支持服务创建时的依赖注入（通过构造函数注入）</li>
 * </ul>
 *
 * <p>工厂类的依赖注入应该通过构造函数实现，而不是通过create方法参数，
 * 这样可以提高代码的可测试性，不依赖服务注册机制。</p>
 *
 * @param <T> 服务类型泛型，表示工厂创建的服务实例类型
 * @author jimichan
 * @since 1.0.0
 */
@FunctionalInterface
public interface ServiceFactory<T> {
    /**
     * 创建服务实例
     *
     * <p>创建并返回一个新的服务实例。具体的创建逻辑由实现类决定，
     * 可以是单例创建、原型创建或其他自定义创建逻辑。</p>
     *
     * <p>工厂类的依赖应该通过构造函数注入，这样可以提高代码的可测试性。</p>
     *
     * @return 新创建的服务实例，具体实现类决定是否返回null
     */
    T create();
}
