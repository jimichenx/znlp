package dev.znlp.base.bintrie;

/**
 * Trie树匹配器接口，用于在文本中查找匹配的词语。
 * <p>
 * 该接口定义了匹配器的基本操作，支持在文本中迭代查找匹配的词语，
 * 并获取匹配词语的参数和位置信息。
 * <p>
 * 匹配器通常用于分词、关键词提取等场景，可以高效地扫描文本并找出
 * 所有在Trie树中存在的词语。
 *
 * @param <T> 匹配词语关联的参数类型
 * @author jimichan
 */
public interface TrieTreeMatcher<T> {

    /**
     * 获取下一个匹配的词语。
     * <p>
     * 该方法会从当前位置开始查找下一个匹配的词语，并返回匹配的字符串。
     * 如果没有更多匹配，则返回null。
     *
     * @return 下一个匹配的词语字符串，如果没有更多匹配则返回null
     */
    String next();

    /**
     * 获取当前匹配词语的全部参数。
     * <p>
     * 参数是在构建Trie树时与词语关联的值对象。
     *
     * @return 当前匹配词语的参数对象，如果没有则返回null
     */
    T getParams();

    /**
     * 获取当前匹配词语中指定索引的参数。
     * <p>
     * 如果参数对象是数组或列表类型，则返回指定索引的元素；
     * 否则返回null。
     *
     * @param i 参数索引
     * @return 指定索引的参数值（转换为字符串），如果不存在则返回null
     */
    String getParam(int i);

    /**
     * 获取当前匹配词语在文本中的偏移量（起始位置）。
     *
     * @return 匹配词语在文本中的偏移量
     */
    int getOffset();
}
